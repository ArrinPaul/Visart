"""Combine schema.sql and the migrations into setup.sql, safe to run more than once.

Usage:  python supabase/make_setup_sql.py
"""

import re
from pathlib import Path

HERE = Path(__file__).parent
PARTS = [HERE / "schema.sql", *sorted((HERE / "migrations").glob("*.sql"))]
POLICY = re.compile(r'create policy\s+("[^"]+")\s+on\s+([\w.]+)', re.IGNORECASE)


def build() -> str:
    out = ["-- Generated by make_setup_sql.py. Paste the whole file into the Supabase SQL editor.",
           "-- Runs as one transaction: if anything fails, nothing is changed.", "", "begin;"]
    for part in PARTS:
        sql = part.read_text(encoding="utf-8")
        # "create policy" has no "if not exists", so drop first to allow a second run.
        sql = POLICY.sub(lambda m: f"drop policy if exists {m[1]} on {m[2]};\n{m[0]}", sql)
        out += ["", f"-- ===== {part.relative_to(HERE).as_posix()} =====", sql.rstrip()]
    out += ["", "commit;", "",
            "-- Check: every table should be listed with rls = true.",
            "select relname as table_name, relrowsecurity as rls from pg_class",
            "where relnamespace = 'public'::regnamespace and relkind = 'r' order by relname;", ""]
    return "\n".join(out)


if __name__ == "__main__":
    (HERE / "setup.sql").write_text(build(), encoding="utf-8")
    print("wrote supabase/setup.sql from", len(PARTS), "files")
